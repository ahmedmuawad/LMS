<?php

declare(strict_types=1);

namespace App\Core\Admin\Fields;

/**
 * أيقونة — تُنتقى من لوحة رموز، ويبقى الإدخال اليدوي متاحاً.
 *
 * أيقونات المنصّة رموز يونيكود وإيموجي لا أصناف خطّ أيقونات (ADR-002:
 * لا اعتماد خارجي في الواجهة)، فالمنتقي لوحةٌ من الرموز نفسها لا قائمة
 * أسماء. ومن يعرف الرمز الذي يريد يكتبه ولا ينتظر أن يجده في اللوحة.
 */
final class IconField extends Field
{
    /**
     * لوحة الرموز — مجموعات مسمّاة بالعربية ليبحث فيها المستخدم بكلمته.
     * أُخذ الصفّ الهندسي من مفردات قوائم اللوحة نفسها فيتّسق ما يختاره
     * المشترك مع ما تعرضه المنصّة.
     *
     * @var array<string, list<string>>
     */
    public const PALETTE = [
        'هندسي' => ['◧', '◨', '◩', '◪', '◫', '◈', '◆', '◇', '◔', '◕', '◐', '◑', '▤', '▦', '▩', '▢', '▭', '☗', '⌗', '⌂'],
        'حالة' => ['✓', '✔', '☑', '✗', '★', '☆', '⚡', '❓', '❝', '✎', '⚙', '☰', '⏱', '◷', '⇄', '↩', '↪', '⇢', '％'],
        'تعليم' => ['📚', '📖', '🎓', '📝', '✏️', '🧠', '🔬', '🧮', '🗂️', '📐', '🏫', '👩‍🏫', '🎯', '💡', '🏆', '🥇', '🎖️', '📜'],
        'وسائط' => ['▶', '🎬', '🎧', '🎤', '📷', '🖼️', '📹', '🔊', '📻', '💿'],
        'تجارة' => ['🛒', '🛍️', '💳', '💰', '🧾', '🏷️', '📦', '🚚', '🎁', '💎'],
        'تواصل' => ['💬', '📣', '🔔', '✉️', '📞', '👥', '👤', '🤝', '❤️', '👍'],
        'وقت ومكان' => ['📅', '🗓️', '⏰', '🌍', '🏛️', '🏢', '📍', '🌐', '🚩', '🔖'],
    ];

    public function component(): string
    {
        return 'admin.fields.icon';
    }

    public function props(): array
    {
        return ['palette' => self::PALETTE];
    }

    /**
     * ثمانية محارف تكفي إيموجي مركّباً (رمز + مُعدِّل + وصلة صفرية)
     * ولا تكفي كلمة — فالحقل يبقى أيقونةً لا عنواناً.
     */
    public function validationRules(string $context): array
    {
        $rules = parent::validationRules($context);
        $rules[] = 'string';
        $rules[] = 'max:8';

        return array_values(array_unique($rules));
    }
}
